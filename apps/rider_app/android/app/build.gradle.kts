// Secrets are read from android/local.properties (not committed), Gradle properties or the environment.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
fun secret(name: String): String =
    (project.findProperty(name) as String?) ?: localProperties.getProperty(name) ?: System.getenv(name) ?: ""

// Release signing: create android/key.properties (see README). Falls back to debug signing.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

